// Regenerates src/shims/icons.ts from every "mdi:<name>" literal in src/,
// so the ha-icon shim bundles exactly the icons the panel uses and nothing
// else. Run `npm run icons` after adding an icon; `npm run build` runs it
// automatically.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as mdi from "@mdi/js";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const names = new Set();
for (const file of walk("src")) {
  if (!file.endsWith(".ts") || file.endsWith("icons.ts")) continue;
  for (const match of readFileSync(file, "utf8").matchAll(/mdi:([a-z0-9-]+)/g)) names.add(match[1]);
}

const camel = (name) => "mdi" + name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const sorted = [...names].sort();
const missing = sorted.filter((name) => !(camel(name) in mdi));
if (missing.length) {
  console.error(`Unknown mdi icons: ${missing.join(", ")}`);
  process.exit(1);
}

writeFileSync(
  "src/shims/icons.ts",
  [
    "// Generated by scripts/gen-icons.mjs - do not edit by hand.",
    `import { ${sorted.map(camel).join(", ")} } from "@mdi/js";`,
    "",
    "export const ICONS: Record<string, string> = {",
    ...sorted.map((name) => `  "mdi:${name}": ${camel(name)},`),
    "};",
    "",
  ].join("\n")
);
console.log(`Wrote ${sorted.length} icons`);
