import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('../src/ha-api.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { parseHustleState } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const assignment = {id:'a',member_id:'kid',chore_definition_id:'chore',status:'assigned',due_date:'2026-09-30',payout_cents:175};
const member = {entity_id:'sensor.kid',state:'0',attributes:{hustle_key:'pending_earnings',member_id:'kid',potential_cents:175,assignments:[assignment]}};
const dynamic = {entity_id:'sensor.assignment',state:'unavailable',attributes:{chore_assignment_id:'a',member_id:'kid',due_date:'2026-09-30'}};
const parse = states => parseHustleState({states});
assert.equal(parse({member}).choreAssignments[0].status,'assigned');
assert.equal(parse({member}).choreAssignments[0].payoutCents,175);
assert.equal(parse({member,dynamic}).choreAssignments.length,1);
member.attributes.assignments=[];
assert.equal(parse({member,dynamic}).choreAssignments.length,0);
delete member.attributes.assignments;
dynamic.state='assigned';
assert.equal(parse({member,dynamic}).choreAssignments.length,1);
console.log('PASS: missing/unavailable dynamic entities, deduplication, cleared snapshots, legacy fallback');
